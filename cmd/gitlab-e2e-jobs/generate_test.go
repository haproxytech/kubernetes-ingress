// TestRenderEmitsANoopJobWhenNothingIsSelected guards the child pipeline
// against being empty, which GitLab treats as a hard error.
func TestRenderEmitsANoopJobWhenNothingIsSelected(t *testing.T) {
	out, err := render(buildPipeline(nil, nil, nil))
	require.NoError(t, err)
	assert.Contains(t, out, "e2e-no-jobs:")
	assert.NotContains(t, out, ".kind_deployment")
}

// TestEveryGeneratedJobCarriesARule is the regression guard for the empty
// child pipeline: without an explicit rule GitLab applies the legacy
// only: [branches, tags] default and drops every job from an MR-ref pipeline.
func TestEveryGeneratedJobCarriesARule(t *testing.T) {
	for name, p := range map[string]childPipeline{
		"jobs":   buildPipeline(twoShardJobSet(), fourTests(), []string{"go-r1"}),
		"no-ops": buildPipeline(nil, nil, nil),
	} {
		out, err := render(p)
		require.NoError(t, err, name)

		parsed := map[string]any{}
		require.NoError(t, yaml.Unmarshal([]byte(out), &parsed), name)
		jobs := 0
		for key, value := range parsed {
			job, ok := value.(map[string]any)
			if !ok || strings.HasPrefix(key, ".") {
				continue
			}
			jobs++
			assert.NotNil(t, job["rules"], "%s: job %q has no rules", name, key)
		}
		assert.Positive(t, jobs, name)
	}
}

func TestRenderedPipelineIsValidYAML(t *testing.T) {
	out, err := render(buildPipeline(twoShardJobSet(), fourTests(), []string{"go-r1", "go-r2"}))
	require.NoError(t, err)

	parsed := map[string]any{}
	require.NoError(t, yaml.Unmarshal([]byte(out), &parsed))
	assert.Contains(t, parsed, "e2e_k8s:sequential-1")
	assert.Contains(t, parsed, "e2e_k8s:sequential-2")
	assert.Equal(t, []any{"e2e_k8s"}, parsed["stages"])
}

// TestParallelSplitKeepsOnePackageListSoGoTestRunsThemConcurrently is the
// guard for the parallel tag: splitting it per test would serialise packages
// that are meant to share a cluster at the same time.
func TestParallelSplitKeepsOnePackageListSoGoTestRunsThemConcurrently(t *testing.T) {
	jobs := []JobSet{{
		Name:   "e2e_k8s",
		Stage:  "e2e_k8s",
		Splits: []Split{{Tag: "e2e_parallel", Mode: "parallel", Shards: 1}},
	}}
	cases := []TestCase{
		{Tag: "e2e_parallel", Package: "./a", Name: "TestA"},
		{Tag: "e2e_parallel", Package: "./b", Name: "TestB"},
		{Tag: "e2e_parallel", Package: "./b", Name: "TestC"},
	}
	p := buildPipeline(jobs, cases, nil)
	require.Len(t, p.Legs, 1)

	got := map[string]string{}
	for _, v := range p.Legs[0].Variables {
		got[v.Name] = v.Value
	}
	assert.Equal(t, "parallel", got["E2E_MODE"])
	assert.Equal(t, "^(TestA|TestB|TestC)$", got["E2E_RUN"])
	assert.Equal(t, "./a ./b", got["E2E_PACKAGES"])
	assert.NotContains(t, got, "E2E_TESTS")
}

func TestDuplicateNamesFindsATestNameSharedByTwoPackages(t *testing.T) {
	cases := []TestCase{
		{Package: "./https", Name: "TestHTTPSSuite"},
		{Package: "./https-runtime", Name: "TestHTTPSSuite"},
		{Package: "./cors", Name: "TestCorsSuite"},
	}
	assert.Equal(t, []string{"TestHTTPSSuite"}, duplicateNames(cases))
	assert.Empty(t, duplicateNames(cases[1:]))
}
