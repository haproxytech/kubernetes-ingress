func twoShardJobSet() []JobSet {
	return []JobSet{{
		Name:      "e2e_k8s",
		Stage:     "e2e_k8s",
		When:      "mr_or_push",
		Splits:    []Split{{Tag: "e2e_sequential", Mode: "sequential", Shards: 2}},
		Variables: map[string]string{"K8S_VERSION": "v1.34.0"},
	}}
}

func fourTests() []TestCase {
	return []TestCase{
		{Tag: "e2e_sequential", Package: "./deploy/tests/e2e/cors", Name: "TestCorsSuite"},
		{Tag: "e2e_sequential", Package: "./deploy/tests/e2e/crd", Name: "TestGlobalSuite"},
		{Tag: "e2e_sequential", Package: "./deploy/tests/e2e/crd-tcp", Name: "TestTCPSuite"},
		{Tag: "e2e_sequential", Package: "./deploy/tests/e2e/tls-auth", Name: "TestTLSAuthSuite"},
		{Tag: "e2e_parallel", Package: "./deploy/tests/e2e/cookie-persistence", Name: "TestCookieSuite"},
	}
}

func TestBuildPipelineMakesOneJobPerShardAndPinsInOrder(t *testing.T) {
	p := buildPipeline(twoShardJobSet(), fourTests(), []string{"go-r1", "go-r2"})
	require.Len(t, p.Legs, 2)
	assert.Equal(t, []string{"e2e_k8s"}, p.Stages)
	assert.Equal(t, "e2e_k8s:sequential-1", p.Legs[0].Name)
	assert.Equal(t, "go-r1", p.Legs[0].Tag)
	assert.Equal(t, "e2e_k8s:sequential-2", p.Legs[1].Name)
	assert.Equal(t, "go-r2", p.Legs[1].Tag)
}

// TestBuildPipelineDealsEveryTestExactlyOnce is the safety net for the split:
// losing or duplicating a test would silently change what the pipeline covers.
func TestBuildPipelineDealsEveryTestExactlyOnce(t *testing.T) {
	p := buildPipeline(twoShardJobSet(), fourTests(), nil)

	seen := []string{}
	for _, l := range p.Legs {
		for _, v := range l.Variables {
			if v.Name == "E2E_TESTS" {
				seen = append(seen, strings.Fields(v.Value)...)
			}
		}
	}
	assert.ElementsMatch(t, []string{
		"./deploy/tests/e2e/cors:TestCorsSuite",
		"./deploy/tests/e2e/crd:TestGlobalSuite",
		"./deploy/tests/e2e/crd-tcp:TestTCPSuite",
		"./deploy/tests/e2e/tls-auth:TestTLSAuthSuite",
	}, seen)
}

func TestBuildPipelineSkipsASplitWithNoMatchingTests(t *testing.T) {
	jobs := []JobSet{{
		Name:   "e2e_k8s",
		Stage:  "e2e_k8s",
		Splits: []Split{{Tag: "e2e_absent", Shards: 2}},
	}}
	p := buildPipeline(jobs, fourTests(), nil)
	assert.Empty(t, p.Legs)
	assert.Empty(t, p.Stages)
}

